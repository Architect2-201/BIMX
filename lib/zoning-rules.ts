export type ZoneCode =
  | "R-1" | "R-2" | "R-3" // საცხოვრებელი ზონები (მაგალითი — გადაამოწმე ნამდვილი კოდები)
  | "C-1" | "C-2"          // კომერციული/საქმიანი ზონები
  | "M-1"                  // შერეული გამოყენების ზონა
  | "GB"                   // მწვანე/დაცული ზონა
  | "UNKNOWN";

export interface ZoneRule {
  zoneCode: ZoneCode;
  zoneNameKa: string;

  /** K-1 — განაშენიანების ინტენსივობის კოეფიციენტი (ჯამური სართულფართობის
   *  შეფარდება ნაკვეთის ფართობთან). null = მონაცემი დაუდასტურებელია. */
  k1: number | null;

  /** K-2 — განაშენიანების მინიმალური ინტენსივობის/სხვა კოეფიციენტი
   *  (ზუსტი განმარტება დამოკიდებულია მოქმედ რედაქციაზე — გადაამოწმე). */
  k2: number | null;

  /** მაქსიმალური სიმაღლე მეტრებში ან სართულების რაოდენობა */
  maxHeightM: number | null;
  maxFloors: number | null;

  /** მინიმალური ნაკვეთის ფართობი მშენებლობისთვის (მ²) */
  minPlotAreaSqm: number | null;

  /** უკან დახევის მინიმალური მანძილები (მ) */
  setbacks: {
    front: number | null;
    side: number | null;
    rear: number | null;
  };

  /** დასაშვები ფუნქციური დანიშნულებები ამ ზონაში */
  permittedUses: string[];

  /** პირობითად დასაშვები (საჭიროებს დამატებით თანხმობას/პროცედურას) */
  conditionalUses: string[];

  /** სპეციალური შეზღუდვები/ვალდებულებები (თავისუფალი ტექსტი) */
  specialRestrictions: string[];

  /** წყარო + გადამოწმების თარიღი — ᲡᲐᲕᲐᲚᲓᲔᲑᲣᲚᲝᲐ შევსებამდე გამოქვეყნებისთვის */
  source: {
    documentTitleKa: string;
    matsneUrl: string;
    verifiedAt: string | null; // ISO date, ან null თუ ჯერ არ გადამოწმებულა
  };
}

