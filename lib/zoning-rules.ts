export function getZoneRule(zoneCode: ZoneCode): ZoneRule | null {
  return ZONE_RULES.find((z) => z.zoneCode === zoneCode) ?? null;
}

/** ვალიდაცია: გაფრთხილება, თუ ვინმე შეეცდება გამოიყენოს დაუდასტურებელი მონაცემი */
export function isZoneRuleVerified(rule: ZoneRule): boolean {
  return rule.source.verifiedAt !== null && rule.k1 !== null && rule.maxHeightM !== null;
}
